import { build } from 'esbuild';
import assert from 'node:assert/strict';
import fs from 'node:fs';
fs.mkdirSync('work', { recursive: true });
await build({ entryPoints: ['src/account/library.ts'], outfile: 'work/account-library.mjs', bundle: true, format: 'esm', platform: 'node' });
const { emptyLibrary, flatten, expand, diff, entryKey, addStats, statsDelta } = await import('../work/account-library.mjs');
const track = id => ({ id, title: id, artists: [{ name: 'Artist' }] });
const base = emptyLibrary();
base.likes = [{ track: track('a'), addedAt: 1 }];
base.playlists = [{ id: 'p', name: 'Playlist', createdAt: 1, tracks: [{ track: track('a'), addedAt: 1 }] }];
assert.deepEqual(expand(flatten(base).values()), base);
const remote = flatten(base);
const remoteAdd = { collection: 'likes', item_id: 'b', value: { track: track('b'), addedAt: 2 }, deleted: false };
remote.set(entryKey(remoteAdd), remoteAdd);
const local = structuredClone(base); local.likes = [];
const edits = diff(flatten(base), flatten(local));
for (const row of edits) remote.set(entryKey(row), row);
assert.deepEqual(expand(remote.values()).likes.map(x => x.track.id), ['b'], 'Removing a local favourite must preserve an unseen addition from another device');
const a = { sec: 10, days: { '2026-10-28': 10 }, plays: { a: { track: track('a'), count: 1, sec: 10 } } };
const b = { sec: 25, days: { '2026-10-28': 25 }, plays: { a: { track: track('a'), count: 1, sec: 25 } } };
assert.deepEqual(addStats(a, statsDelta(a, b)), b);
assert.equal(statsDelta(b, b).sec, 0, 'Hydrating shared totals must not count listening twice');
const statsRows = [a, b].map((stats, i) => ({ collection: 'stats', item_id: String(i), value: { month: '2026-10', stats }, deleted: false }));
assert.equal(expand(statsRows).stats['2026-10'].sec, 35, 'Independent device shards are summed once');
console.log('Account library: round-trip, concurrent additions/deletions, playlist tracks and listening totals passed');
